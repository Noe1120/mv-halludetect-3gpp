"""把 paper/supplementary/ESM_1.md（Online Resource 1）编译成 PDF：paper/supplementary/ESM_1.pdf。

用法（在 build_latex.py 之后运行）：
  python scripts/build_supplement.py

补充材料没有交叉引用正文的标签，文献只有自己的一条，所以单独排版，不走 BibTeX。
沿用 build_latex.py 的行内转换（公式、粗体、代码、表格），模板用 sn-jnl 的 pdflatex 选项。
"""
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

from _common import ROOT

import build_latex as BL

SRC = ROOT / "paper" / "supplementary" / "ESM_1.md"
OUT = ROOT / "paper" / "supplementary" / "ESM_1.pdf"


def table(rows, caption):
    head, *body = rows
    n = len(head)
    L = ">{\\raggedright\\arraybackslash}p"
    if n == 2:
        spec = f"{L}{{0.24\\textwidth}}{L}{{0.70\\textwidth}}"
    else:   # 表 S2（6 列）
        spec = (f"{L}{{0.05\\textwidth}}{L}{{0.22\\textwidth}}{L}{{0.15\\textwidth}}{L}{{0.13\\textwidth}}"
                f"{L}{{0.10\\textwidth}}{L}{{0.19\\textwidth}}")
    cell = lambda c: inline(c)
    tex = ["\\begin{table}[h]", "\\centering", "\\caption{" + cell(caption) + "}",
           "{\\setlength{\\tabcolsep}{4pt}\\footnotesize", "\\begin{tabular}{" + spec + "}", "\\toprule",
           " & ".join(cell(c) for c in head) + " \\\\", "\\midrule"]
    tex += [" & ".join(cell(c) for c in r) + " \\\\" for r in body]
    tex += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
    return "\n".join(tex)


def inline(s):
    """行内转换，但对正文的节、表、图、式的引用保留纯文本编号（补充材料里没有这些标签，否则会显示成 ??）。"""
    keep = {}

    def stash(m):
        k = f"\x05{len(keep)}\x06"
        keep[k] = m.group(0)
        return k
    s = re.sub(r"\b(?:Sects?\.|Table|Tables|Fig\.|Eqs?\.)\s+\(?\d[\d.]*\)?(?:–\(?\d[\d.]*\)?)?", stash, s)
    s = BL.convert_inline(s, {})
    for k, v in keep.items():
        s = s.replace(k, BL.tex_escape(v).replace("Sect. ", "Sect.~").replace("Table ", "Table~"))
    return s


def convert(md):
    lines = md.splitlines()
    out, i, caption = [], 0, ""
    in_list = False
    while i < len(lines):
        s = lines[i].strip()
        if s.startswith("```"):
            code = []
            i += 1
            while not lines[i].strip().startswith("```"):
                code.append(lines[i])
                i += 1
            out.append("\\begin{lstlisting}[basicstyle=\\scriptsize\\ttfamily,breaklines=true,columns=fullflexible]\n"
                       + "\n".join(code) + "\n\\end{lstlisting}")
            i += 1
            continue
        m = re.match(r"^\*\*Table (S\d) (.+)\*\*$", s)
        if m:
            caption = m.group(2).rstrip(".")
            i += 1
            continue
        if s.startswith("|"):
            block = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                block.append(lines[i].strip())
                i += 1
            rows = [[c.strip() for c in r.strip("|").split("|")] for r in block if not re.match(r"^\|?\s*:?-{2,}", r)]
            out.append(table(rows, caption))
            continue
        if s.startswith("# "):
            i += 1
            continue
        if s.startswith("## "):
            out.append("\\section*{" + inline(s[3:]) + "}")
        elif s.startswith("### "):
            out.append("\\subsection*{" + inline(s[4:]) + "}")
        elif re.match(r"^\d+\. ", s) and "doi.org" in s:   # 补充材料自己的参考文献
            out.append("\\noindent [" + s.split(".")[0] + "] " + inline(s.split(". ", 1)[1])
                       .replace("https://doi.org/", "\\url{https://doi.org/") + "}")
        elif s:
            out.append(inline(s))
        else:
            out.append("")
        i += 1
    return "\n".join(out)


def main():
    md = SRC.read_text(encoding="utf-8")
    title = re.search(r"^\*\*(.+?)\*\*$", md, re.M).group(1)
    author = md.split("\n\n")[2].strip()
    body_md = md[md.index("This file contains"):]
    body = convert(body_md)
    tex = r"""%% Generated by scripts/build_supplement.py from paper/supplementary/ESM_1.md
\documentclass[pdflatex,sn-mathphys-num]{sn-jnl}
\usepackage{amsmath,amssymb}
\usepackage{booktabs}
\usepackage{array}
\usepackage{listings}
\usepackage{textcomp}
\usepackage{xcolor}
\raggedbottom
\renewcommand{\thetable}{S\arabic{table}}
\begin{document}
\begin{center}
{\Large\bfseries Online Resource 1}\\[6pt]
{\large """ + BL.tex_escape(title) + r"""}\\[6pt]
""" + BL.tex_escape(author) + r"""
\end{center}
\vspace{6pt}
""" + body + r"""
\end{document}
"""
    with tempfile.TemporaryDirectory(dir="D:/claude-home/cache") as tmp:
        shutil.copyfile(BL.OUT / "sn-jnl.cls", Path(tmp) / "sn-jnl.cls")
        (Path(tmp) / "esm.tex").write_text(tex, encoding="utf-8")
        cmd = ["pdflatex", "--disable-installer", "-interaction=nonstopmode", "-halt-on-error", "esm.tex"]
        for _ in range(2):
            r = subprocess.run(cmd, cwd=tmp, capture_output=True, text=True, encoding="utf-8", errors="replace",
                               timeout=300)
        log = (Path(tmp) / "esm.log").read_text(encoding="utf-8", errors="replace")
        errs = re.findall(r"^! .*$", log, re.M)
        over = len(re.findall(r"Overfull \\hbox", log))
        pages = re.search(r"Output written on esm\.pdf \((\d+) pages", log)
        if pages:
            shutil.copyfile(Path(tmp) / "esm.pdf", OUT)
        shutil.copyfile(Path(tmp) / "esm.tex", OUT.with_suffix(".tex"))
    print("Online Resource 1:", OUT if pages else "未生成", "| 页数:", pages.group(1) if pages else "-",
          "| 错误:", errs[:3] or "无", "| overfull:", over)


if __name__ == "__main__":
    main()
